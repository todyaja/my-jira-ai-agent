// folderBody is the text of the parent pages created to group documents.
const folderBody = "Documents published by the Jira AI Agent are filed under this page."

// Page is a published page.
type Page struct {
	ID  string
	URL string
}

// PublishPageUnder writes markdown as the page titled title below the chain
// of parent pages named by parents, e.g. {"RFCs", "RFCs 2026"}, creating any
// parent that does not exist yet. The first parent goes under ParentPageID,
// or the space root. An existing page with the title is updated in place.
// Confluence titles are unique per space, so parents must be too.
func (c *Client) PublishPageUnder(ctx context.Context, parents []string, title, markdown string) (Page, error) {
	spaceID, err := c.lookupSpaceID(ctx)
	if err != nil {
		return Page{}, err
	}
	parentID := strings.TrimSpace(c.ParentPageID)
	for _, parent := range parents {
		if parentID, err = c.ensurePage(ctx, spaceID, parentID, parent); err != nil {
			return Page{}, err
		}
	}
	published, err := c.publish(ctx, spaceID, parentID, title, MarkdownToStorage(markdown))
	if err != nil {
		return Page{}, err
	}
	pageURL, err := c.webURL(published)
	if err != nil {
		return Page{}, err
	}
	return Page{ID: published.ID, URL: pageURL}, nil
}

// ensurePage returns the id of the page titled title, creating it under
// parentID with the folder text when there is none.
func (c *Client) ensurePage(ctx context.Context, spaceID, parentID, title string) (string, error) {
	existing, found, err := c.findPage(ctx, spaceID, title, false)
	if err != nil {
		return "", err
	}
	if found {
		return existing.ID, nil
	}
	created, err := c.publish(ctx, spaceID, parentID, title, "<p>"+folderBody+"</p>")
	if err != nil {
		return "", err
	}
	return created.ID, nil
}

// publish creates the page titled title under parentID, or updates its
// content when it exists.
func (c *Client) publish(ctx context.Context, spaceID, parentID, title, storage string) (pageResponse, error) {
	existing, found, err := c.findPage(ctx, spaceID, title, false)
	if err != nil {
		return pageResponse{}, err
	}
	page := pageRequest{Status: "current", Title: title, Body: pageBody{Representation: "storage", Value: storage}}
	var published pageResponse
	if found {
		page.ID = existing.ID
		page.Version = &pageVersion{Number: existing.Version.Number + 1, Message: "Regenerated by Jira AI Agent"}
		err = c.sendJSON(ctx, http.MethodPut, "/wiki/api/v2/pages/"+url.PathEscape(existing.ID), "PUT page", page, &published)
	} else {
		page.SpaceID = spaceID
		page.ParentID = parentID
		err = c.sendJSON(ctx, http.MethodPost, "/wiki/api/v2/pages", "POST page", page, &published)
	}
	if err != nil {
		return pageResponse{}, err
	}
	if published.ID == "" {
		published.ID = existing.ID
	}
	return published, nil
}

// AttachFile uploads the file at path to the page, replacing an attachment
// with the same file name.
func (c *Client) AttachFile(ctx context.Context, pageID, path string) error {
	file, err := os.Open(path)
	if err != nil {
		return fmt.Errorf("attach file: %w", err)
	}
	defer file.Close()

	var body bytes.Buffer
	form := multipart.NewWriter(&body)
	part, err := form.CreateFormFile("file", filepath.Base(path))
	if err != nil {
		return fmt.Errorf("attach file: %w", err)
	}
	if _, err := io.Copy(part, file); err != nil {
		return fmt.Errorf("attach file: %w", err)
	}
	if err := form.WriteField("minorEdit", "true"); err != nil {
		return fmt.Errorf("attach file: %w", err)
	}
	if err := form.Close(); err != nil {
		return fmt.Errorf("attach file: %w", err)
	}

	// The v2 API cannot upload attachments; v1 PUT creates or updates one.
	request, err := http.NewRequestWithContext(ctx, http.MethodPut, strings.TrimRight(c.BaseURL, "/")+"/wiki/rest/api/content/"+url.PathEscape(pageID)+"/child/attachment", &body)
	if err != nil {
		return fmt.Errorf("PUT attachment: %w", err)
	}
	request.SetBasicAuth(c.Email, c.Token)
	request.Header.Set("Content-Type", form.FormDataContentType())
	request.Header.Set("X-Atlassian-Token", "no-check")
	request.Header.Set("Accept", "application/json")
	return c.expectOK(request, "PUT attachment")
}

// AddLabel labels the page, e.g. with its Jira key, so every document of a
// ticket can be found by label. Adding a label the page has is a no-op.
func (c *Client) AddLabel(ctx context.Context, pageID, label string) error {
	var response any
	labels := []map[string]string{{"prefix": "global", "name": strings.ToLower(label)}}
	return c.sendJSON(ctx, http.MethodPost, "/wiki/rest/api/content/"+url.PathEscape(pageID)+"/label", "POST label", labels, &response)
}

func (c *Client) expectOK(request *http.Request, operation string) error {
	httpClient := c.HTTPClient
	if httpClient == nil {
		httpClient = http.DefaultClient
	}
	response, err := httpClient.Do(request)
	if err != nil {
		return fmt.Errorf("%s: %w", operation, err)
	}
	defer response.Body.Close()
	_, _ = io.Copy(io.Discard, response.Body)
	if response.StatusCode < http.StatusOK || response.StatusCode >= http.StatusMultipleChoices {
		return fmt.Errorf("%s: Confluence returned HTTP %d", operation, response.StatusCode)
	}
	return nil
}
